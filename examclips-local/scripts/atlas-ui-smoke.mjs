import {chromium} from 'playwright-core';
import {existsSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';

const executablePath=[process.env.CHROME_PATH,'/usr/bin/google-chrome','/usr/bin/chromium',chromium.executablePath()].filter(Boolean).find(existsSync);
const browser=await chromium.launch({executablePath,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const origin=process.env.EXAMCLIPS_ORIGIN||'http://127.0.0.1:5173/';
mkdirSync('test-results',{recursive:true});
const errors=[];
const subtitle=['1','00:00:00,000 --> 00:00:02,000','Контейнеры применяются для изоляции приложений. Образ содержит программу и зависимости.','',
 '2','00:00:02,000 --> 00:00:04,000','В результате контейнер запускает приложение в одинаковом окружении. Настройки остаются воспроизводимыми.'].join('\n');
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin);
 assert.ok(await page.locator('#atlas-library').isVisible(),'Atlas library is the initial screen');
 assert.equal(await page.locator('.library-item').count(),0,'No fictional lecture cards');
 assert.doesNotMatch(await page.locator('body').innerText(),/lovable/i);
 await page.screenshot({path:'test-results/atlas-library-empty.png',fullPage:true});
 await page.locator('#atlas-new-lecture').click();
 assert.ok(await page.locator('#wizard-step-1').isVisible());
 await page.locator('#video-file').setInputFiles('test-fixture.mp4');
 await page.waitForFunction(()=>!document.querySelector('#import-srt').disabled);
 await page.locator('#wizard-next').click();
 assert.ok(await page.locator('#wizard-step-2').isVisible());
 await page.locator('#language').selectOption('ru');
 await page.locator('#wizard-next').click();
 assert.ok(await page.locator('#wizard-step-3').isVisible());
 assert.match(await page.locator('#wizard-summary').innerText(),/Русский/);
 assert.equal(await page.locator('#story-keep,#topic-preset').count(),0);
 await page.locator('#srt-file').setInputFiles({name:'atlas.srt',mimeType:'text/plain',buffer:Buffer.from(subtitle)});
 await page.waitForFunction(()=>document.querySelector('#wizard-srt-status').textContent.includes('SRT'));
 await page.locator('#workflow-start').click();
 await page.waitForFunction(()=>document.querySelector('#app').dataset.phase==='results');
 assert.ok(await page.locator('#microtopic-overview').isVisible());
 assert.ok(await page.locator('#atlas-coverage-track').isVisible());
 assert.equal(await page.locator('.microtopic-card').count(),1);
 await page.screenshot({path:'test-results/atlas-catalog.png',fullPage:true});
 await page.locator('.microtopic-card-title').first().click();
 assert.ok(await page.locator('#atlas-original-slot #player').isVisible());
 assert.ok(await page.locator('#microtopic-preview').isVisible());
 assert.ok(await page.locator('#atlas-local-track').isVisible());
 await page.locator('#clip-title').fill('Сохранённый урок с новым интерфейсом');
 await page.locator('#clip-start').fill('0.2');
 await page.locator('#clip-end').fill('3.8');
 await page.locator('#approve-topic').click();
 await page.screenshot({path:'test-results/atlas-detail.png',fullPage:true});
 await page.locator('.top-navigation [data-editor-tab="timeline"]').click();
 for(let i=0;i<7;i++)await page.locator('#timeline-zoom-in').click();
 assert.equal(await page.locator('#timeline-zoom-label').textContent(),'8×');
 await page.locator('.top-navigation [data-editor-tab="clip"]').click();
 await page.locator('.microtopic-card-title').first().click();
 await page.waitForFunction(()=>document.querySelector('#autosave-state').textContent.includes('✓'));
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#app')?.dataset.phase==='results');
 assert.ok(await page.locator('#microtopic-detail').isVisible(),'Detail reopens after reload');
 assert.equal(await page.locator('#clip-title').inputValue(),'Сохранённый урок с новым интерфейсом');
 assert.equal(await page.locator('#clip-start').inputValue(),'0.2');
 assert.equal(await page.locator('#clip-end').inputValue(),'3.8');
 assert.equal(await page.locator('#language').inputValue(),'ru');
 assert.equal(await page.locator('#timeline-zoom-label').textContent(),'8×');
 await page.locator('#clip-title').fill('Правка перед мгновенным возвратом');
 await page.locator('#back-to-library').click();
 await page.waitForFunction(()=>!document.querySelector('#atlas-library').hidden);
 assert.equal(await page.locator('.library-item').count(),1);
 await page.screenshot({path:'test-results/atlas-library-saved.png',fullPage:true});
 await page.locator('.library-item-actions button').first().click();
 await page.waitForFunction(()=>document.querySelector('#app')?.dataset.phase==='results');
 if(!await page.locator('#microtopic-detail').isVisible())await page.locator('.microtopic-card-title').first().click();
 assert.equal(await page.locator('#clip-title').inputValue(),'Правка перед мгновенным возвратом');
 await page.locator('#atlas-theme').click();
 assert.equal(await page.locator('html').getAttribute('data-ui-theme'),'light');
 await page.screenshot({path:'test-results/atlas-detail-light.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const dimensions=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(dimensions.scroll<=dimensions.client+2,'Mobile page must not overflow: '+JSON.stringify(dimensions));
 assert.ok(await page.locator('#microtopic-back').isVisible(),'Mobile can return to the grid');
 await page.screenshot({path:'test-results/atlas-detail-mobile.png',fullPage:true});
 await page.locator('#microtopic-back').click();
 assert.ok(await page.locator('#microtopic-overview').isVisible());
 assert.deepEqual(errors,[]);
 console.log('ATLAS_UI_SMOKE_SUCCESS: real library, wizard, grid, comparison, edits, approval, zoom, reload, immediate exit, settings, light theme and mobile');
}finally{await browser.close()}
